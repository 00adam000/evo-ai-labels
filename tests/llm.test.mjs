// Tests for js/llm.js and js/explain-service.js using a fake fetch, so no
// network or API key is needed. Plain Node, no dependencies:
//   node tests/llm.test.mjs

import { readFileSync } from "node:fs";
import { llmExplain, EXPLANATION_TOOL } from "../js/llm.js";
import { getExplanation, clearExplanationCache } from "../js/explain-service.js";

const { posts } = JSON.parse(readFileSync(new URL("../data/posts.json", import.meta.url)));
const byId = Object.fromEntries(posts.map((p) => [p.id, p]));
const KEY = "test-key-not-real";

let failed = 0;
let total = 0;
function check(pass, name, detail = "") {
  total++;
  if (!pass) failed++;
  console.log(`${pass ? "PASS" : "FAIL"}  ${name}${detail ? `  (${detail})` : ""}`);
}

// Fake fetch helpers. Each records the requests it receives.
function fakeFetch(respond) {
  const calls = [];
  const fn = async (url, init) => {
    calls.push({ url, init, body: JSON.parse(init.body) });
    return respond(url, init);
  };
  fn.calls = calls;
  return fn;
}
const jsonResponse = (status, body) => ({ ok: status >= 200 && status < 300, status, json: async () => body });
const toolUse = (input) => jsonResponse(200, {
  type: "message", stop_reason: "tool_use",
  content: [{ type: "tool_use", id: "toolu_test", name: "give_explanation", input }],
});

const GOOD_P2 = {
  summary: "Part of this photo was changed with AI. It is signed by City Life Daily.",
  what_ai_did: ["The sky was replaced with a generated night sky using generative fill."],
  what_is_unknown: ["Whether the caption is accurate. Provenance describes the image, not the caption."],
  cited_fields: ["signer", "actions[1]"],
};
const ai = (fetchImpl, extra = {}) => ({ mode: "ai", apiKey: KEY, fetchImpl, ...extra });

// (a) valid tool_use response is accepted and shown with source "llm"
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse(GOOD_P2));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "llm" && notice === null && result.summary === GOOD_P2.summary,
    "(a) valid tool_use response is shown with source llm", `source=${result?.source}, notice=${notice}`);
  await getExplanation(byId.p2, ai(f));
  check(f.calls.length === 1, "(a2) second open of the same post uses the cache", `${f.calls.length} API call(s)`);
}

// (b) citation to actions[9] falls back with a "failed safety checks" notice
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse({ ...GOOD_P2, cited_fields: ["signer", "actions[9]"] }));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /failed safety checks/.test(notice) && /actions\[9\]/.test(notice),
    "(b) citation to actions[9] falls back to offline", notice);
}

// (c) response saying the post is fake falls back
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse({ ...GOOD_P2, summary: "This post is fake. The sky was generated by AI." }));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /failed safety checks/.test(notice) && /fake/.test(notice),
    "(c) 'post is fake' summary falls back to offline", notice);
}

// (c2) field names such as "(actions[1])" in shown text fall back, as seen in the first live run
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse({ ...GOOD_P2, what_ai_did: ["The sky was replaced with a generated night sky (actions[1])."] }));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /failed safety checks/.test(notice) && /internal text/.test(notice),
    "(c2) '(actions[1])' in what_ai_did falls back to offline", notice);
}

// (d) HTTP 401 falls back with an "unavailable" notice that includes the status
clearExplanationCache();
{
  const f = fakeFetch(() => jsonResponse(401, { type: "error", error: { type: "authentication_error", message: "invalid x-api-key" } }));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /unavailable/.test(notice) && /401/.test(notice),
    "(d) HTTP 401 falls back with status in notice", notice);
  await getExplanation(byId.p2, ai(f));
  check(f.calls.length === 2, "(d2) service errors are not cached, so reopening retries", `${f.calls.length} API calls`);
}

// (e) timeout falls back (fake fetch never answers; it only rejects when aborted)
clearExplanationCache();
{
  const hang = (url, init) => new Promise((_, reject) => {
    init.signal.addEventListener("abort", () => reject(new DOMException("aborted", "AbortError")));
  });
  const t0 = Date.now();
  const { result, notice } = await getExplanation(byId.p2, ai(fakeFetch(hang), { timeoutMs: 50 }));
  check(result?.source === "mock" && /unavailable \(timeout\)/.test(notice),
    "(e) timeout falls back to offline", `${notice} after ${Date.now() - t0} ms`);
}
{
  // The default timeout is 15 s: check that llmExplain sets its timer to that value.
  const seen = [];
  const realSetTimeout = globalThis.setTimeout;
  globalThis.setTimeout = (fn, ms) => { seen.push(ms); return realSetTimeout(() => {}, 0); };
  try { await llmExplain(byId.p2, { apiKey: KEY, fetchImpl: fakeFetch(() => toolUse(GOOD_P2)) }); }
  finally { globalThis.setTimeout = realSetTimeout; }
  check(seen.includes(15000), "(e2) default timeout is 15 s", `timer set to ${seen.join(", ")} ms`);
}

// (f) request body contains no caption, author or ground_truth (all 7 posts).
// The record's "signer" can legitimately repeat the author's name, so the
// provenance is compared to the post's record as a whole, and only the rest
// of the request is searched for the post's other fields.
{
  const leaks = [];
  for (const post of posts) {
    const f = fakeFetch(() => toolUse(GOOD_P2));
    await llmExplain(post, { apiKey: KEY, fetchImpl: f });
    const body = f.calls[0].body;
    const user = JSON.parse(body.messages[0].content);
    if (JSON.stringify(user.provenance) !== JSON.stringify(post.provenance ?? null)) leaks.push(`${post.id} provenance altered`);
    const rest = JSON.stringify({ ...body, messages: [{ ...body.messages[0], content: { ...user, provenance: "<record>" } }] });
    for (const [what, value] of [["caption", post.text], ["author", post.author], ["handle", post.handle], ["image_alt", post.image_alt], ["ground_truth", "ground_truth"]]) {
      if (rest.includes(value)) leaks.push(`${post.id} ${what}`);
    }
  }
  check(leaks.length === 0, "(f) request body has no caption, author or ground_truth (all 7 posts)", leaks.join(", ") || "none found");
}

// (g) request uses the forced tool, correct headers and settings
{
  const f = fakeFetch(() => toolUse(GOOD_P2));
  await llmExplain(byId.p3, { apiKey: KEY, fetchImpl: f });
  const { url, init, body } = f.calls[0];
  const h = init.headers;
  check(body.tool_choice?.type === "tool" && body.tool_choice?.name === "give_explanation"
    && body.tools.length === 1 && body.tools[0].name === "give_explanation",
    "(g) tool_choice forces give_explanation", JSON.stringify(body.tool_choice));
  const schema = EXPLANATION_TOOL.input_schema;
  check(schema.additionalProperties === false && schema.required.join() === "summary,what_ai_did,what_is_unknown,cited_fields",
    "(g2) tool schema: all four fields required, no extra properties");
  check(url === "https://api.anthropic.com/v1/messages" && init.method === "POST"
    && h["x-api-key"] === KEY && h["anthropic-version"] === "2023-06-01"
    && h["content-type"] === "application/json" && h["anthropic-dangerous-direct-browser-access"] === "true",
    "(g3) endpoint and headers are correct");
  check(body.model === "claude-haiku-5-5" && body.max_tokens === 600 && !("temperature" in body),
    "(g4) default model claude-haiku-5-5, max_tokens 600, no temperature", `model=${body.model}`);
  const user = JSON.parse(body.messages[0].content);
  check(user.label_level === "AI-generated" && Object.keys(user).join() === "label_level,provenance",
    "(g5) user message holds only the label level and the record", Object.keys(user).join(", "));
}

// Extra failure paths
clearExplanationCache();
{
  const f = fakeFetch(() => jsonResponse(200, { type: "message", stop_reason: "end_turn", content: [{ type: "text", text: "Here you go" }] }));
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /no tool_use block/.test(notice), "missing tool_use block falls back", notice);
}
clearExplanationCache();
{
  const f = fakeFetch(() => { throw new TypeError("Failed to fetch"); });
  const { result, notice } = await getExplanation(byId.p2, ai(f));
  check(result?.source === "mock" && /unavailable \(network error\)/.test(notice), "network failure falls back", notice);
}
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse(GOOD_P2));
  const { result, notice } = await getExplanation(byId.p2, { mode: "ai", apiKey: "", fetchImpl: f });
  check(result?.source === "mock" && /needs an API key/.test(notice) && f.calls.length === 0,
    "AI mode with no key makes no request and falls back", notice);
}
clearExplanationCache();
{
  const f = fakeFetch(() => toolUse(GOOD_P2));
  const { result, notice } = await getExplanation(byId.p5, { mode: "offline", fetchImpl: f });
  check(result?.source === "mock" && notice === null && f.calls.length === 0, "offline mode never calls the API");
}

console.log(`\n${total - failed}/${total} passed`);
process.exit(failed ? 1 : 0);
